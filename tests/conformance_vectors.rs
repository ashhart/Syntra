struct TempDir(PathBuf);
impl TempDir {
    fn new(tag: &str) -> Self {
        let dir = std::env::temp_dir().join(format!(
            "lycan-conformance-{tag}-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .subsec_nanos()
        ));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        Self(dir)
    }
    fn path(&self) -> &Path {
        &self.0
    }
}
impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

#[test]
fn conformance_vectors_capsule_containers() {
    let manifest = load_manifest();
    for entry in manifest["capsule_vectors"].as_array().unwrap() {
        run_capsule_vector(entry);
    }
}

fn run_capsule_vector(entry: &Value) {
    let id = entry["id"].as_str().unwrap();
    let scenario = entry["scenario"].as_str().unwrap();
    let exp = &entry["expectations"];
    let program_bytes = read_manifest_vector(&load_manifest(), "valid-with-strings");

    let tmp = TempDir::new(id);
    let lyc = tmp.path().join("base.lyc");
    std::fs::write(&lyc, &program_bytes).unwrap();
    let dir = tmp.path().join(format!("{id}.lycap"));
    capsule::create(
        &lyc.to_string_lossy(),
        &dir.to_string_lossy(),
        "conformance",
        "spec conformance vector",
        vec![],
    )
    .unwrap_or_else(|e| panic!("{id}: capsule create failed: {e}"));

    // scenario mutations (tamper surface = on-disk files post-create)
    match scenario {
        "create" => {}
        "tamper_program" => {
            append_file(&dir.join("program.lyc"), &[0x00]);
        }
        "tamper_inspect" => {
            append_file(&dir.join("inspect.json"), b"\n");
        }
        "remove_manifest" => {
            std::fs::remove_file(dir.join("manifest.json")).unwrap();
        }
        "remove_policy" => {
            std::fs::remove_file(dir.join("policy.json")).unwrap();
        }
        "corrupt_format_string" => {
            let m = dir.join("manifest.json");
            let text = std::fs::read_to_string(&m).unwrap();
            std::fs::write(&m, text.replace("lycan-capsule-v1", "no-such-format-v1")).unwrap();
        }
        "reformat_policy_json" => {
            let p = dir.join("policy.json");
            let v: Value = serde_json::from_str(&std::fs::read_to_string(&p).unwrap()).unwrap();
            // Semantically identical, compact serialization (no space after ':').
            std::fs::write(&p, serde_json::to_string(&v).unwrap()).unwrap();
        }
        other => panic!("{id}: unknown scenario {other}"),
    }

    let result = capsule::verify_capsule(&dir.to_string_lossy());
    match exp["verify_capsule"].as_str().unwrap() {
        "ok" => {
            result.unwrap_or_else(|e| panic!("{id}: verify_capsule unexpectedly failed: {e}"));
        }
        v => {
            let want = v.strip_prefix("err:").unwrap();
            let err = result
                .err()
                .unwrap_or_else(|| panic!("{id}: verify_capsule unexpectedly succeeded"));
            assert!(
                err.contains(want),
                "{id}: verify error missing pinned substring\nwant: {want}\n got: {err}"
            );
        }
    }

    if let Some(pins) = exp.get("pins") {
        apply_capsule_pins(&dir, pins, &program_bytes, id);
    }
}

fn read_manifest_vector(manifest: &Value, id: &str) -> Vec<u8> {
    let entry = manifest["vectors"]
        .as_array()
        .unwrap()
        .iter()
        .find(|v| v["id"].as_str() == Some(id))
        .unwrap_or_else(|| panic!("manifest vector {id} missing"));
    read_vector_file(entry)
}

fn append_file(path: &Path, bytes: &[u8]) {
    use std::io::Write;
    let mut f = std::fs::OpenOptions::new().append(true).open(path).unwrap();
    f.write_all(bytes).unwrap();
}

fn sha256_hex(bytes: &[u8]) -> String {
    let mut h = Sha256::new();
    h.update(bytes);
    h.finalize().iter().map(|b| format!("{b:02x}")).collect()
}

fn apply_capsule_pins(dir: &Path, pins: &Value, program_bytes: &[u8], id: &str) {
    if pins.get("program_identical").and_then(|v| v.as_bool()) == Some(true) {
        // §8 req 1: program.lyc byte-identical to the input
        assert_eq!(
            std::fs::read(dir.join("program.lyc")).unwrap(),
            program_bytes,
            "{id}: program.lyc not byte-identical to input"
        );
    }
    if let Some(files) = pins.get("files_exact") {
        // §8 req 1: exactly these five files under {name}.lycap/
        let mut got: Vec<String> = std::fs::read_dir(dir)
            .unwrap()
            .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
            .collect();
        got.sort();
        let want: Vec<String> = files
            .as_array()
            .unwrap()
            .iter()
            .map(|v| v.as_str().unwrap().to_string())
            .collect();
        assert_eq!(got, want, "{id}: capsule file set");
    }
    if pins
        .get("manifest_sha256_of_program")
        .and_then(|v| v.as_bool())
        == Some(true)
    {
        // §8 req 2: program_sha256 equals SHA-256 over the on-disk program bytes
        let manifest = std::fs::read_to_string(dir.join("manifest.json")).unwrap();
        let on_disk = std::fs::read(dir.join("program.lyc")).unwrap();
        assert!(
            manifest.contains(&sha256_hex(&on_disk)),
            "{id}: manifest program_sha256 does not match on-disk program.lyc"
        );
    }
    for key in ["manifest_contains", "policy_contains"] {
        if let Some(list) = pins.get(key) {
            let file = if key == "manifest_contains" {
                "manifest.json"
            } else {
                "policy.json"
            };
            let text = std::fs::read_to_string(dir.join(file)).unwrap();
            for want in list.as_array().unwrap() {
                let want = want.as_str().unwrap();
                assert!(text.contains(want), "{id}: {file} missing literal {want}");
            }
        }
    }
}

