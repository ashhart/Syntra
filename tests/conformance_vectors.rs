#[test]
fn magic_and_format_version_constants_are_pinned() {
    // Direct pin on the constants themselves (they are private, so pin the
    // declarations textually…)...
    let src = include_str!("../src/graph.rs");
    assert!(
        src.contains("const MAGIC: [u8; 4] = [0x4C, 0x59, 0x43, 0x4E];"),
        "graph.rs MAGIC constant drifted from 4C 59 43 4E"
    );
    assert!(
        src.contains("const FORMAT_VERSION: u8 = 5;"),
        "graph.rs FORMAT_VERSION drifted from 5"
    );
    // …and behaviorally: the real encoder emits magic+version 5 at offsets 0..5.
    let head = NeuralGraph::new().to_bytes();
    assert_eq!(
        &head[..5],
        &[0x4C, 0x59, 0x43, 0x4E, 0x05],
        "encoder header prefix drifted"
    );
    // Manifest-level pin matches the harness constants.
    let m = load_manifest();
    assert_eq!(m["magic"].as_array().unwrap().len(), 4);
    let mmagic: Vec<u8> = m["magic"]
        .as_array()
        .unwrap()
        .iter()
        .map(|v| v.as_u64().unwrap() as u8)
        .collect();
    assert_eq!(mmagic, MAGIC);
    assert_eq!(
        m["graph_format_version"].as_u64().unwrap() as u8,
        FORMAT_VERSION
    );
}

