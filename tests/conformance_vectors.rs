//! Machine-checkable conformance vectors for the Lycan spec family.
//!
//! Sources of truth:
//!   docs/lycan/spec/graph-binary-format.md §15 "Conformance requirements"
//!   docs/lycan/spec/capsule-format.md     §8  "Conformance requirements"
//!
//! Every `.bin` under tests/fixtures/conformance/vectors/ is COMMITTED and
//! asserted byte-identical to what the generator below produces
//! (`committed_fixtures_match_generator`). CI runs against the committed
//! bytes. To refresh intentionally:
//!
//!   CONFORMANCE_REGENERATE=1 cargo test --release --test conformance_vectors regenerate_fixtures
//!
//! "conformance-v0.1-pins-CURRENT" marks assertions that pin CURRENT
//! (lenient / lenient-broken) decoder behavior that a future versioned spec
//! may tighten; flipping them MUST be a deliberate break.
//!
//! Grammar/learning vectors land later with their specs — the manifest
//! schema here (id/file/expectations/pins/notes + scenario-based non-byte
//! vectors) is designed to absorb them without restructuring.
//!
//! NOTE (capsule side, spec §6 / conformance req 6): NO signing vectors are
//! provided because NO signing exists anywhere in the pipeline — integrity is
//! SHA-256 + substring checks only. A manifest signature today MUST be
//! ignored; presence of signing vectors here in the future means signing was
//! added and this note is stale.

