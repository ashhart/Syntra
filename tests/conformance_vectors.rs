/// Load the committed manifest; if fixtures are missing entirely (fresh tree
/// before `add`, not CI), regenerate so the suite still runs — committed
/// bytes are always what CI asserts.
fn load_manifest() -> Value {
    let p = manifest_path();
    if !p.exists() {
        build_fixtures();
    }
    let text = std::fs::read_to_string(&p).expect("manifest.json readable");
    serde_json::from_str(&text).expect("manifest.json is valid JSON")
}

fn read_vector_file(entry: &Value) -> Vec<u8> {
    let path = fixtures_root().join(entry["file"].as_str().unwrap());
    if !path.exists() {
        build_fixtures();
    }
    std::fs::read(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

