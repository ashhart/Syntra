// ── byte-builder helpers for HAND-ASSEMBLED (illegal / patched) vectors ──
// The legal vectors all come from REAL encoder calls (NeuralGraph::to_bytes);
// these exist only because a conforming encoder MUST NOT be able to emit the
// corrupt shapes the reject-lattice vectors need (§14: encoders MUST NOT
// produce lenient-corner files).

fn put_u32(b: &mut Vec<u8>, v: u32) {
    b.extend_from_slice(&v.to_le_bytes());
}
fn put_f64(b: &mut Vec<u8>, v: f64) {
    b.extend_from_slice(&v.to_le_bytes());
}
fn put_u64(b: &mut Vec<u8>, v: u64) {
    b.extend_from_slice(&v.to_le_bytes());
}
fn put_i64(b: &mut Vec<u8>, v: i64) {
    b.extend_from_slice(&v.to_le_bytes());
}

/// 29-byte header (graph spec §2). One argument per header field.
#[allow(clippy::too_many_arguments)]
fn put_header(
    b: &mut Vec<u8>,
    version: u8,
    nodes: u32,
    edges: u32,
    state_size: u32,
    strings: u32,
    flags: u32,
    entry: u32,
) {
    b.extend_from_slice(&MAGIC);
    b.push(version);
    put_u32(b, nodes);
    put_u32(b, edges);
    put_u32(b, state_size);
    put_u32(b, strings);
    put_u32(b, flags);
    put_u32(b, entry);
}

/// One node record with EXPLICIT enum bytes (§5), no state slot / annotation.
/// One argument per record field.
#[allow(clippy::too_many_arguments)]
fn put_raw_node(
    b: &mut Vec<u8>,
    id: u32,
    op: u8,
    operands: &[u8],
    operand_count: u32,
    weights: &[f64],
    bias: f64,
    wk: u8,
    contract: u8,
    objective: u8,
) {
    put_u32(b, id);
    b.push(op);
    put_u32(b, operand_count);
    b.extend_from_slice(operands);
    put_u32(b, weights.len() as u32);
    for w in weights {
        put_f64(b, *w);
    }
    put_f64(b, bias);
    put_u64(b, 0); // activation_count
    b.push(0); // has_state = false
    b.push(wk);
    b.push(0); // has_annotation = false
    b.push(contract);
    b.push(objective);
}

fn raw_noderef(id: u32) -> Vec<u8> {
    let mut o = vec![0x01u8];
    put_u32(&mut o, id);
    o
}
fn raw_int(v: i64) -> Vec<u8> {
    let mut o = vec![0x10u8];
    put_i64(&mut o, v);
    o
}
fn raw_float(v: f64) -> Vec<u8> {
    let mut o = vec![0x11u8];
    put_f64(&mut o, v);
    o
}

